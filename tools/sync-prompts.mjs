// Writes src/app/prompts.js from docs/PROMPT.md and docs/PROMPT.pl.md: the page copies exactly the text that the repository shows.
//   node tools/sync-prompts.mjs            writes src/app/prompts.js
//   node tools/sync-prompts.mjs --check    exits 1 when the file is not what the two documents say (the tests run this check)
// The documents are the source: edit them, then run this tool and commit both.
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const OUT = join(root, 'src/app/prompts.js');
const clean = (s) => s.replace(/\r\n/g, '\n').replace(/\s+$/, '');
const lines = (name) => clean(readFileSync(join(root, 'docs', name), 'utf8')).split('\n');
const block = (name, rows) => `export const ${name} = [\n${rows.map((l) => `  ${JSON.stringify(l)},`).join('\n')}\n].join('\\n');\n`;

export function render() {
  return `// Generated by tools/sync-prompts.mjs from docs/PROMPT.md and docs/PROMPT.pl.md: do not edit by hand (a test checks that it is current).
// The prompts that a person pastes into an AI chat together with a picture of a floor plan; the Load plan box of the page copies them.
${block('PROMPT_EN', lines('PROMPT.md'))}${block('PROMPT_PL', lines('PROMPT.pl.md'))}
// The prompt in the language of the page (Polish for 'pl', English for everything else).
export const promptFor = (lang) => (lang === 'pl' ? PROMPT_PL : PROMPT_EN);
`;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const want = render();
  if (process.argv.includes('--check')) {
    let have = '';
    try { have = readFileSync(OUT, 'utf8'); } catch { /* missing counts as stale */ }
    if (have !== want) { console.error('src/app/prompts.js is not current: run node tools/sync-prompts.mjs'); process.exit(1); }
    console.log('src/app/prompts.js is current');
  } else {
    writeFileSync(OUT, want);
    console.log(`wrote ${OUT} (${want.length} characters)`);
  }
}
